/**
 * Scope for checks on the extensions of GraphQL responses
 */
export const graphqlExtensions: GraphQlJsonScope = wrapGraphQlJsonScope(
  jvmGraphQlDsl.graphqlExtensions as JvmGraphQlJsonScope
);
