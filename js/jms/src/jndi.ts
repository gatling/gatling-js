import { Wrapper } from "@gatling.io/core";

import { JmsDsl as JvmJmsDsl } from "@gatling.io/jvm-types";

import JvmJmsJndiConnectionFactoryBuilder = io.gatling.javaapi.jms.JmsJndiConnectionFactoryBuilder;
import JvmJmsJndiConnectionFactoryBuilderBase = io.gatling.javaapi.jms.JmsJndiConnectionFactoryBuilder$Base;
import JvmJmsJndiConnectionFactoryBuilderContextFactory = io.gatling.javaapi.jms.JmsJndiConnectionFactoryBuilder$ContextFactory;
import JvmJmsJndiConnectionFactoryBuilderUrl = io.gatling.javaapi.jms.JmsJndiConnectionFactoryBuilder$Url;

/**
 * A ConnectionFactory looked up with JNDI, built with {@link jmsJndiConnectionFactory}
 *
 * <p>Immutable, so all methods return a new occurrence and leave the original unmodified.
 */
export interface JmsJndiConnectionFactoryBuilder extends Wrapper<JvmJmsJndiConnectionFactoryBuilder> {}

export namespace JmsJndiConnectionFactoryBuilder {
  export interface Base {
    /**
     * Define the JNDI name of the ConnectionFactory
     *
     * @param connectionFactoryName - the name
     * @returns the next DSL step
     */
    connectionFactoryName(connectionFactoryName: string): Url;
  }

  export interface Url {
    /**
     * Define the url of the JNDI provider, typically the broker's url
     *
     * @param url - the url
     * @returns the next DSL step
     */
    url(url: string): ContextFactory;
  }

  export interface ContextFactory {
    /**
     * Define the credentials used to connect to the JNDI provider, see
     * javax.naming.Context.SECURITY_PRINCIPAL and SECURITY_CREDENTIALS
     *
     * @param user - the user
     * @param password - the password
     * @returns a new ContextFactory instance
     */
    credentials(user: string, password: string): ContextFactory;

    /**
     * Define a property of the JNDI InitialContext, see your JMS client's documentation
     *
     * @param key - the property key
     * @param value - the property value
     * @returns a new ContextFactory instance
     */
    property(key: string, value: string): ContextFactory;

    /**
     * Define the class name of the JNDI InitialContextFactory, provided by your JMS client, for
     * example org.apache.activemq.artemis.jndi.ActiveMQInitialContextFactory for ActiveMQ Artemis
     *
     * @param contextFactory - the class name
     * @returns a JmsJndiConnectionFactoryBuilder, to pass to jms.connectionFactory()
     */
    contextFactory(contextFactory: string): JmsJndiConnectionFactoryBuilder;
  }

  export const wrapBase = (_underlying: JvmJmsJndiConnectionFactoryBuilderBase): Base => ({
    connectionFactoryName: (connectionFactoryName: string) =>
      wrapUrl(_underlying.connectionFactoryName(connectionFactoryName))
  });

  const wrapUrl = (_underlying: JvmJmsJndiConnectionFactoryBuilderUrl): Url => ({
    url: (url: string) => wrapContextFactory(_underlying.url(url))
  });

  const wrapContextFactory = (_underlying: JvmJmsJndiConnectionFactoryBuilderContextFactory): ContextFactory => ({
    credentials: (user: string, password: string) => wrapContextFactory(_underlying.credentials(user, password)),
    property: (key: string, value: string) => wrapContextFactory(_underlying.property(key, value)),
    contextFactory: (contextFactory: string) => ({ _underlying: _underlying.contextFactory(contextFactory) })
  });
}

/**
 * Bootstrap the configuration of a ConnectionFactory looked up with JNDI, to pass to
 * jms.connectionFactory(). The JMS client of your broker must be declared in the
 * "gatling.jvmDependencies" section of package.json.
 */
export const jmsJndiConnectionFactory: JmsJndiConnectionFactoryBuilder.Base = JmsJndiConnectionFactoryBuilder.wrapBase(
  // static fields aren't generated by java2ts
  (JvmJmsDsl as any).jmsJndiConnectionFactory
);
