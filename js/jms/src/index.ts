import { JmsDsl as JvmJmsDsl, JmsProtocolBuilder$Base as JvmJmsProtocolBuilderBaseStatic } from "@gatling.io/jvm-types";

import JvmJms = io.gatling.javaapi.jms.Jms;

/**
 * DSL for JMS actions
 */
export interface Jms {
  /**
   * Create a builder for actions that send a message, without waiting for any reply
   *
   * @returns the next DSL step
   */
  send(): JmsSendActionBuilder.Queue;

  /**
   * Create a builder for actions that send a request and wait for its reply
   *
   * @returns the next DSL step
   */
  requestReply(): JmsRequestReplyActionBuilder.Queue;
}

const wrapJms = (_underlying: JvmJms): Jms => ({
  send: () => JmsSendActionBuilder.wrapQueue(_underlying.send()),
  requestReply: () => JmsRequestReplyActionBuilder.wrapQueue(_underlying.requestReply())
});

export interface JmsApply {
  /**
   * Bootstrap a builder for a JMS action
   *
   * @param name - the action name, expressed as a Gatling Expression Language String
   * @returns the next DSL step
   */
  (name: string): Jms;

  /**
   * Bootstrap a builder for a JMS action
   *
   * @param name - the action name, expressed as a function
   * @returns the next DSL step
   */
  (name: (session: Session) => string): Jms;
}

const jmsApply = (name: Expression<string>): Jms =>
  wrapJms(typeof name === "function" ? JvmJmsDsl.jms(underlyingSessionTo(name)) : JvmJmsDsl.jms(name));

// JmsDsl.jms doesn't get properly generated by java2ts because of conflicts with methods of the same name, but it's
// this very instance
const jvmJmsProtocolBuilderBase = JvmJmsProtocolBuilderBaseStatic.INSTANCE;

/**
 * The entrypoint of the JMS DSL: jms.connectionFactory(...) bootstraps a protocol, jms("name") an
 * action
 */
export const jms: JmsApply & JmsProtocolBuilderBase = Object.assign(
  jmsApply,
  wrapJmsProtocolBuilderBase(jvmJmsProtocolBuilderBase)
);
