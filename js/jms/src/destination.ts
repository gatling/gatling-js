import { Expression, Session, Wrapper, underlyingSessionTo } from "@gatling.io/core";

import { JmsDestination as JvmJmsDestinationClass, JmsDsl as JvmJmsDsl } from "@gatling.io/jvm-types";

import JvmJmsDestination = io.gatling.javaapi.jms.JmsDestination;

/**
 * A JMS destination, a queue or a topic
 */
export interface JmsDestination extends Wrapper<JvmJmsDestination> {}

export interface JmsDestinationFunction {
  /**
   * @param name - the name, expressed as a Gatling Expression Language String
   * @returns a JmsDestination
   */
  (name: string): JmsDestination;

  /**
   * @param name - the name, expressed as a function
   * @returns a JmsDestination
   */
  (name: (session: Session) => string): JmsDestination;
}

/**
 * Create a JMS queue destination
 */
export const queue: JmsDestinationFunction = (name: Expression<string>): JmsDestination => ({
  _underlying: typeof name === "function" ? JvmJmsDsl.queue(underlyingSessionTo(name)) : JvmJmsDsl.queue(name)
});

/**
 * Create a JMS topic destination
 */
export const topic: JmsDestinationFunction = (name: Expression<string>): JmsDestination => ({
  _underlying: typeof name === "function" ? JvmJmsDsl.topic(underlyingSessionTo(name)) : JvmJmsDsl.topic(name)
});

// static fields aren't generated by java2ts

/**
 * A temporary queue, created for each action using it, which lives as long as the JMS connection
 */
export const temporaryQueue: JmsDestination = { _underlying: (JvmJmsDestinationClass as any).TemporaryQueue };

/**
 * A temporary topic, created for each action using it, which lives as long as the JMS connection
 */
export const temporaryTopic: JmsDestination = { _underlying: (JvmJmsDestinationClass as any).TemporaryTopic };
